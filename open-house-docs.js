  const MONTHS = ["มกราคม","กุมภาพันธ์","มีนาคม","เมษายน","พฤษภาคม","มิถุนายน","กรกฎาคม","สิงหาคม","กันยายน","ตุลาคม","พฤศจิกายน","ธันวาคม"];
  const WEEKDAYS = ["อาทิตย์","จันทร์","อังคาร","พุธ","พฤหัสบดี","ศุกร์","เสาร์"];
  const DOTS = "...............................................";

  function parts(iso){ const [y, m, d] = String(iso || "").slice(0, 10).split("-").map(Number); return { y, m, d }; }
  // "16 พฤศจิกายน 2569" (เลขอารบิกตามแบบฟอร์มของโรงเรียน)
  function thDate(iso){ const x = parts(iso); return x.y ? x.d + " " + MONTHS[x.m - 1] + " " + (x.y + 543) : DOTS; }
  // "ศุกร์ที่ 20 พฤศจิกายน 2569" (ใช้ต่อท้าย "ในวัน")
  function thDayDate(iso){
    const x = parts(iso); if (!x.y) return DOTS;
    return WEEKDAYS[new Date(Date.UTC(x.y, x.m - 1, x.d)).getUTCDay()] + "ที่ " + thDate(iso);
  }
  // "ก" / "ก และ ข" / "ก, ข และ ค"
  function joinNames(a){
    a = (a || []).map(s => String(s).trim()).filter(Boolean);
    if (!a.length) return DOTS;
    return a.length === 1 ? a[0] : a.slice(0, -1).join(", ") + " และ " + a[a.length - 1];
  }
  const xmlEsc = s => String(s == null ? "" : s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");

  // หมายเหตุ: ไม่แทรกตัวคั่นคำ (U+200B) ในข้อความที่เติม เพราะตัวตัดคำของเบราว์เซอร์ตัดชื่อเฉพาะผิด
  // (เช่น "เซาธ์อีสต์" -> "เซา/ธ์/อีส/ต์") ปล่อยให้ Word ตัดคำไทยเอง
  function fill(xml, vals){
    for (const k in vals) xml = xml.split("{{" + k + "}}").join(xmlEsc(String(vals[k])));
    return xml;
  }
  // รหัสย่อหน้า (w14:paraId/textId/anchorId) ห้ามซ้ำในไฟล์เดียว -> ลบทิ้ง (เป็นค่าเสริม Word สร้างใหม่เอง)
  const stripIds = s => s.replace(/ w14:(?:paraId|textId|anchorId)="[^"]*"/g, "");

  function bytes(b64){ const bin = atob(b64), u = new Uint8Array(bin.length); for (let i = 0; i < bin.length; i++) u[i] = bin.charCodeAt(i); return u; }

  async function open(){
    if (typeof JSZip === "undefined") throw new Error("โหลดตัวสร้างไฟล์ไม่สำเร็จ ตรวจอินเทอร์เน็ตแล้วลองใหม่");
    const zip = await JSZip.loadAsync(bytes(TPL_B64));
    const xml = await zip.file("word/document.xml").async("string");
    const b0 = xml.indexOf("<w:body>") + "<w:body>".length;
    const s0 = xml.lastIndexOf("<w:sectPr");
    const mark = xml.indexOf("{{SPLIT}}");
    const m0 = xml.lastIndexOf("<w:p>", mark), m1 = xml.indexOf("</w:p>", mark) + "</w:p>".length;
    if (b0 < 8 || s0 < 0 || mark < 0 || m0 < b0) throw new Error("แม่แบบเอกสารไม่ถูกต้อง");
    return { zip, head: xml.slice(0, b0), memo: xml.slice(b0, m0), parent: xml.slice(m1, s0), tail: xml.slice(s0) };
  }
  async function pack(t, bodyXml){
    t.zip.file("word/document.xml", t.head + stripIds(bodyXml) + t.tail);
    return t.zip.generateAsync({ type: "blob", compression: "DEFLATE",
      mimeType: "application/vnd.openxmlformats-officedocument.wordprocessingml.document" });
  }
  function common(d){
    return {
      UNI: d.uni || DOTS, PLACE: d.place || d.uni || DOTS, TIME: d.time || DOTS,
      DAYDATE: thDayDate(d.eventDate), DATE: thDate(d.docDate),
      TEACHERS: joinNames(d.teachers), POSITION: d.position || "ครูแนะแนว"
    };
  }

  // d = {uni, place, time, eventDate, docDate, teachers[], position, signer, head, students:[{name, room}]}
  async function buildMemo(d){
    if (!d.students || !d.students.length) throw new Error("ยังไม่มีนักเรียนที่เลือกไปกับโรงเรียน");
    const t = await open();
    let memo = fill(t.memo, Object.assign(common(d), { SIGNER: d.signer || DOTS.slice(0, 46), HEAD: d.head || DOTS }));
    // แถวรายชื่อ: ทำซ้ำย่อหน้าแม่แบบ 1 ย่อหน้าต่อ 1 คน (เลขลำดับขึ้นเองจากรายการลำดับเลขของ Word)
    const i = memo.indexOf("{{S_NAME}}");
    const r0 = memo.lastIndexOf("<w:p ", i), r1 = memo.indexOf("</w:p>", i) + "</w:p>".length;
    const rowTpl = memo.slice(r0, r1);
    const rows = d.students.map(s => fill(rowTpl, { S_NAME: s.name || DOTS, S_CLASS: s.room || "" })).join("");
    return pack(t, memo.slice(0, r0) + rows + memo.slice(r1));
  }

  // d = {..., pno, director, students:[{name, room}]} -> 1 ฉบับต่อนักเรียน 1 คน ขึ้นหน้าใหม่ทุกฉบับ
  async function buildParentLetters(d){
    if (!d.students || !d.students.length) throw new Error("ยังไม่มีนักเรียนที่เลือกไปกับโรงเรียน");
    const t = await open();
    const base = fill(t.parent, Object.assign(common(d), { PNO: d.pno || "……", DIRECTOR: d.director || DOTS }));
    const out = d.students.map((s, n) => {
      let x = fill(base, { STUDENT: s.name || DOTS, CLS: String(s.room || "").replace(/^ม\.?\s*/, "") || "......../......." });
      if (n > 0){
        x = x.replace("<w:pPr>", "<w:pPr><w:pageBreakBefore/>");                 // ฉบับถัดไปขึ้นหน้าใหม่
        x = x.replace(/<v:shapetype[\s\S]*?<\/v:shapetype>/, "");                  // นิยามรูปทรงตราครุฑมีครั้งเดียวพอ
        x = x.split("_x0000_s1026").join("_x0000_s" + (3000 + n));                  // รหัสรูปตราครุฑห้ามซ้ำ
        x = x.replace(/ObjectID="_(\d+)"/, (m, v) => 'ObjectID="_' + (Number(v) + n) + '"');
      }
      return x;
    });
    return pack(t, out.join(""));
  }

  return { buildMemo, buildParentLetters, thDate, thDayDate, joinNames };
