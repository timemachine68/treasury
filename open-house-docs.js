  const stripIds = s => s.replace(/ w14:(?:paraId|textId|anchorId)="[^"]*"/g, "");

  function bytes(b64){ const bin = atob(b64), u = new Uint8Array(bin.length); for (let i = 0; i < bin.length; i++) u[i] = bin.charCodeAt(i); return u; }

  async function open(){
    if (typeof JSZip === "undefined") throw new Error("โหลดตัวสร้างไฟล์ไม่สำเร็จ ตรวจอินเทอร์เน็ตแล้วลองใหม่");
    const zip = await JSZip.loadAsync(bytes(TPL_B64));
    const xml = await zip.file("word/document.xml").async("string");
    const b0 = xml.indexOf("<w:body>") + "<w:body>".length;
    const s0 = xml.lastIndexOf("<w:sectPr");
    const mark = xml.indexOf("{{SPLIT}}");
    const m0 = xml.lastIndexOf("<w:p>", mark), m1 = xml.indexOf("</w:p>", mark) + "</w:p>".length;
    if (b0 < 8 || s0 < 0 || mark < 0 || m0 < b0) throw new Error("แม่แบบเอกสารไม่ถูกต้อง");
    return { zip, head: xml.slice(0, b0), memo: xml.slice(b0, m0), parent: xml.slice(m1, s0), tail: xml.slice(s0) };
  }
  async function pack(t, bodyXml){
    t.zip.file("word/document.xml", t.head + stripIds(bodyXml) + t.tail);
    return t.zip.generateAsync({ type: "blob", compression: "DEFLATE",
      mimeType: "application/vnd.openxmlformats-officedocument.wordprocessingml.document" });
  }
