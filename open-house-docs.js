    const zip = await JSZip.loadAsync(bytes(TPL_B64));
    const xml = await zip.file("word/document.xml").async("string");
    const b0 = xml.indexOf("<w:body>") + "<w:body>".length;
    const s0 = xml.lastIndexOf("<w:sectPr");
    const mark = xml.indexOf("{{SPLIT}}");
    const m0 = xml.lastIndexOf("<w:p>", mark), m1 = xml.indexOf("</w:p>", mark) + "</w:p>".length;
    if (b0 < 8 || s0 < 0 || mark < 0 || m0 < b0) throw new Error("แม่แบบเอกสารไม่ถูกต้อง");
    return { zip, head: xml.slice(0, b0), memo: xml.slice(b0, m0), parent: xml.slice(m1, s0), tail: xml.slice(s0) };
