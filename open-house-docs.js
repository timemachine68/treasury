    const i = memo.indexOf("{{S_NAME}}");
    const r0 = memo.lastIndexOf("<w:p ", i), r1 = memo.indexOf("</w:p>", i) + "</w:p>".length;
    const rowTpl = memo.slice(r0, r1);
    const rows = d.students.map(s => fill(rowTpl, { S_NAME: s.name || DOTS, S_CLASS: s.room || "" })).join("");
