  const MONTHS = ["มกราคม","กุมภาพันธ์","มีนาคม","เมษายน","พฤษภาคม","มิถุนายน","กรกฎาคม","สิงหาคม","กันยายน","ตุลาคม","พฤศจิกายน","ธันวาคม"];
  const WEEKDAYS = ["อาทิตย์","จันทร์","อังคาร","พุธ","พฤหัสบดี","ศุกร์","เสาร์"];
  const DOTS = "...............................................";

  function parts(iso){ const [y, m, d] = String(iso || "").slice(0, 10).split("-").map(Number); return { y, m, d }; }
  // "16 พฤศจิกายน 2569" (เลขอารบิกตามแบบฟอร์มของโรงเรียน)
  function thDate(iso){ const x = parts(iso); return x.y ? x.d + " " + MONTHS[x.m - 1] + " " + (x.y + 543) : DOTS; }
  // "ศุกร์ที่ 20 พฤศจิกายน 2569" (ใช้ต่อท้าย "ในวัน")
  function thDayDate(iso){
    const x = parts(iso); if (!x.y) return DOTS;
    return WEEKDAYS[new Date(Date.UTC(x.y, x.m - 1, x.d)).getUTCDay()] + "ที่ " + thDate(iso);
  }
  // "ก" / "ก และ ข" / "ก, ข และ ค"
  function joinNames(a){
    a = (a || []).map(s => String(s).trim()).filter(Boolean);
    if (!a.length) return DOTS;
    return a.length === 1 ? a[0] : a.slice(0, -1).join(", ") + " และ " + a[a.length - 1];
  }
  const xmlEsc = s => String(s == null ? "" : s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");

  // หมายเหตุ: ไม่แทรกตัวคั่นคำ (U+200B) ในข้อความที่เติม เพราะตัวตัดคำของเบราว์เซอร์ตัดชื่อเฉพาะผิด
