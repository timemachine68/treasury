create table if not exists uni_alumni_stats (
  id uuid primary key default gen_random_uuid(),
  grad_year int not null check (grad_year between 2560 and 2600),
  university_id uuid not null references iv_universities(id) on delete cascade,
  campus text not null default '' check (char_length(campus) <= 120),
  field_group text not null check (char_length(field_group) between 1 and 80),
  n int not null check (n > 0),
  source_note text check (char_length(source_note) <= 300),
  created_at timestamptz not null default now(),
  unique (grad_year, university_id, campus, field_group)
);
alter table uni_alumni_stats enable row level security;
revoke all on uni_alumni_stats from anon;
drop policy if exists "uni_alumni_stats staff read" on uni_alumni_stats;
drop policy if exists "uni_alumni_stats staff write" on uni_alumni_stats;
create policy "uni_alumni_stats staff read" on uni_alumni_stats for select to authenticated using ((select iv_is_staff()));
create policy "uni_alumni_stats staff write" on uni_alumni_stats for all to authenticated using ((select iv_is_staff())) with check ((select iv_is_staff()));
create index if not exists uni_alumni_stats_uni_idx on uni_alumni_stats (university_id);

